import { z } from 'zod';

export const createStaffSchema = z.object({
  tenantId: z.string().min(1, 'Tenant ID is required'),
  campusId: z.string().optional(),
  employeeId: z.string().optional(),
  firstName: z.string().min(2, 'First name must be at least 2 characters'),
  lastName: z.string().min(2, 'Last name must be at least 2 characters'),
  email: z.string().email('Invalid email address'),
  phone: z.string().min(5, 'Phone number must be at least 5 digits'),
  nationalId: z.string().min(3, 'National ID must be at least 3 characters'),
  gender: z.enum(['MALE', 'FEMALE']),
  dateOfBirth: z.string().or(z.date()),
  address: z.string().optional(),
  jobTitle: z.string().min(2, 'Job title is required'),
  department: z.string().min(2, 'Department is required'),
  staffRole: z.enum([
    'ADMINISTRATOR',
    'TEACHER',
    'TEACHER_VACATAIRE',
    'ACCOUNTANT',
    'SECRETARY',
    'LIBRARIAN',
    'IT_SUPPORT',
    'BUS_DRIVER',
    'BUS_ATTENDANT',
    'MATERNELLE_ASSISTANT',
    'CLEANING_STAFF',
    'SECURITY_AGENT',
    'MAINTENANCE',
    'OTHER',
  ]),
  employmentType: z.enum(['FULL_TIME', 'PART_TIME', 'CONTRACT', 'TEMPORARY', 'HOURLY_VACATION']),
  contractType: z.enum(['CDI', 'CDD', 'VACATION', 'ANAPEC']).optional(),
  cnssNumber: z.string().optional(),
  hourlyRate: z.number().positive().optional(),
  assignedZone: z.string().optional(),
  busId: z.string().optional(),
  replacementStaffId: z.string().optional(),
  leaveReason: z.string().optional(),
  status: z.enum(['ACTIVE', 'ON_LEAVE', 'SUSPENDED', 'TERMINATED']).optional(),
  joinDate: z.string().or(z.date()),
  salary: z.number().positive().optional(),
  userId: z.string().optional(),
});

export const createTeacherProfileSchema = z.object({
  tenantId: z.string().min(1, 'Tenant ID is required'),
  staffMemberId: z.string().min(1, 'Staff member ID is required'),
  specialization: z.string().min(2, 'Specialization is required'),
  qualification: z.string().min(2, 'Qualification is required'),
  subjectIds: z.array(z.string()).optional(),
  campusIds: z.array(z.string()).optional(),
  maxWeeklyHours: z.number().positive().optional(),
  bio: z.string().optional(),
});

export const createStudentProfileSchema = z.object({
  tenantId: z.string().min(1, 'Tenant ID is required'),
  campusId: z.string().min(1, 'Campus ID is required'),
  enrolledStudentId: z.string().optional(),
  studentNumber: z.string().optional(),
  firstName: z.string().min(2, 'First name is required'),
  lastName: z.string().min(2, 'Last name is required'),
  nationalId: z.string().min(3, 'National ID is required'),
  dateOfBirth: z.string().or(z.date()),
  gender: z.enum(['MALE', 'FEMALE']),
  bloodGroup: z.string().optional(),
  medicalNotes: z.string().optional(),
  dietaryRestrictions: z.string().optional(),
  educationalStageId: z.string().optional(),
  gradeLevelId: z.string().optional(),
  classGroupId: z.string().optional(),
  status: z.enum(['ACTIVE', 'GRADUATED', 'TRANSFERRED', 'SUSPENDED', 'WITHDRAWN']).optional(),
  joinDate: z.string().or(z.date()),
  address: z.string().optional(),
});

export const createGuardianProfileSchema = z.object({
  tenantId: z.string().min(1, 'Tenant ID is required'),
  firstName: z.string().min(2, 'First name is required'),
  lastName: z.string().min(2, 'Last name is required'),
  email: z.string().email('Invalid email address'),
  phone: z.string().min(5, 'Phone number is required'),
  nationalId: z.string().min(3, 'National ID is required'),
  occupation: z.string().optional(),
  employer: z.string().optional(),
  address: z.string().optional(),
  userId: z.string().optional(),
});

export const createRelationshipSchema = z.object({
  tenantId: z.string().min(1, 'Tenant ID is required'),
  guardianId: z.string().min(1, 'Guardian ID is required'),
  studentProfileId: z.string().min(1, 'Student Profile ID is required'),
  relationType: z.enum(['FATHER', 'MOTHER', 'STEP_PARENT', 'GRANDPARENT', 'LEGAL_GUARDIAN', 'OTHER']),
  isPrimaryContact: z.boolean().optional(),
  isEmergencyContact: z.boolean().optional(),
  canPickup: z.boolean().optional(),
  isFinancialResponsible: z.boolean().optional(),
});
